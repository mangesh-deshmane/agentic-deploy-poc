"""
Render Terraform variables from a resolved request.

No LLM touches this. The agent decided WHAT to deploy; this decides how to
express it, deterministically, from the catalog. That separation is what lets
you tell an audience the AI did not write the infrastructure.
"""

import json
import re
from pathlib import Path

from . import catalog
from .schema import DeployRequest

MANIFEST = Path(".platform-state/bootstrap.json")

TEMPLATE = """# Generated by the agentic deploy platform.
# Request: deploy {app} for {customer} to {env_name} on {cloud}
# Correlation: {correlation_id}
#
# Written from catalog/blueprints.yaml by a template, not by a model.

project_id = "{project_id}"
region     = "{region}"

app      = "{app}"
customer = "{customer}"
env_name = "{env_name}"

image = "{image}"

runtime_service_account = "{runtime_sa}"

min_instance_count = {min_instance_count}
max_instance_count = {max_instance_count}
memory             = "{memory}"
cpu                = "{cpu}"

ttl_hours = {ttl_hours}
protected = false
"""


def project_id() -> str:
    """Read from the bootstrap manifest rather than hardcoding."""
    if MANIFEST.exists():
        return json.loads(MANIFEST.read_text())["project_id"]
    import os

    return os.getenv("POC_PROJECT", "agentic-poc-5b8b")


def slug(value: str, limit: int = 20) -> str:
    """RFC1035-safe. Applied again here even though the schema normalises."""
    s = re.sub(r"[^a-z0-9-]", "-", value.strip().lower())
    s = re.sub(r"-+", "-", s).strip("-")[:limit].rstrip("-")
    if not s or not s[0].isalpha():
        s = f"c-{s}" if s else "demo"
    return s[:limit].rstrip("-")


def render(req: DeployRequest, blueprint_key: str, correlation_id: str,
           image_tag: str = "latest") -> tuple[str, str]:
    """
    Return (filename, contents).

    The filename is also the environment name, which selects the Terraform
    state prefix - so two customers never share state.
    """
    bp = catalog.blueprint(blueprint_key)
    d = catalog.defaults()

    customer = slug(req.customer)
    region = req.region or bp["default_region"]

    env_file = f"{req.env_name.value}-{customer}"
    pid = project_id()

    image = f"{bp['image_repo']}:{image_tag}" if bp.get("image_repo") else ""
    runtime_sa = (
        f"{bp['runtime_service_account']}@{pid}.iam.gserviceaccount.com"
        if bp.get("runtime_service_account")
        else ""
    )

    content = TEMPLATE.format(
        app=req.app.value,
        cloud=req.cloud.value,
        customer=customer,
        env_name=req.env_name.value,
        correlation_id=correlation_id,
        project_id=pid,
        region=region,
        image=image,
        runtime_sa=runtime_sa,
        min_instance_count=d["min_instance_count"],
        max_instance_count=d["max_instance_count"],
        memory=d["memory"],
        cpu=d["cpu"],
        ttl_hours=req.ttl_hours,
    )

    return f"envs/{env_file}.tfvars", content


def summary(req: DeployRequest, blueprint_key: str) -> dict:
    """What the UI shows before asking for confirmation."""
    bp = catalog.blueprint(blueprint_key)
    d = catalog.defaults()
    customer = slug(req.customer)

    return {
        "Application": bp["display_name"],
        "Runtime": f"{bp['language']} on {bp['platform']}",
        "Cloud": req.cloud.value.upper(),
        "Data store": bp["data_store"],
        "Customer": customer,
        "Environment": req.env_name.value,
        "Region": req.region or bp["default_region"],
        "Service name": f"{req.app.value}-{customer}-{req.env_name.value}",
        "Scaling": f"{d['min_instance_count']} to {d['max_instance_count']} (scale to zero)",
        "Resources": f"{d['memory']} / {d['cpu']} vCPU",
        "TTL": f"{req.ttl_hours}h",
        "Estimated cost": "$0.00/month (free tier)",
    }
